// WebRTC Configuration
const rtcConfig = {
  iceServers: [
    { urls: "stun:stun.l.google.com:19302" },
    { urls: "stun:stun1.l.google.com:19302" }
  ]
};

let peerConnection = null;
let pendingCandidates = [];

function createPeerConnection(channel) {
  if (peerConnection) {
    peerConnection.close();
  }
  pendingCandidates = [];

  peerConnection = new RTCPeerConnection(rtcConfig);

  // Dashboards receives camera track
  peerConnection.ontrack = (event) => {
    console.log("📹 Remote camera stream received:", event.streams);
    if (event.streams && event.streams[0]) {
      remoteVideo.srcObject = event.streams[0];
      if (videoSection) videoSection.style.display = "block";
      updateStatus("🟢 User camera connected live", "connected");
    }
  };

  // ICE candidates generated by dashboard
  peerConnection.onicecandidate = (event) => {
    if (event.candidate) {
      console.log("📤 Sending ICE candidate from dashboard");
      channel.send({
        type: "broadcast",
        event: "signal",
        payload: {
          sender: "dashboard",
          type: "ice",
          candidate: event.candidate.toJSON()
        }
      });
    }
  };

  peerConnection.onconnectionstatechange = () => {
    console.log("WebRTC Connection State:", peerConnection.connectionState);
    if (peerConnection.connectionState === "connected") {
      updateStatus("🟢 Live camera connected", "connected");
    } else if (peerConnection.connectionState === "disconnected" || peerConnection.connectionState === "failed") {
      updateStatus("⚠️ Camera connection disconnected", "error");
    }
  };

  return peerConnection;
}

// Subscribe to Supabase Realtime broadcast channel for signaling
const channel = supabase.channel(`webrtc-room-${roomId}`);

channel
  .on("broadcast", { event: "signal" }, async ({ payload }) => {
    if (!payload || payload.sender !== "camera") return;

    console.log("📩 Signal received from camera:", payload.type);

    try {
      // 1. Camera asks if dashboard is ready or announces join
      if (payload.type === "ready") {
        console.log("👋 Camera device joined room");
        updateStatus("📲 Camera joined. Preparing stream...", "waiting");
        channel.send({
          type: "broadcast",
          event: "signal",
          payload: { sender: "dashboard", type: "dashboard-ready" }
        });
        return;
      }

      // 2. Camera sends Offer
      if (payload.type === "offer") {
        console.log("📦 Processing SDP offer from camera");
        const pc = createPeerConnection(channel);

        await pc.setRemoteDescription(new RTCSessionDescription(payload.offer));

        // Flush any candidates received while setting remote description
        while (pendingCandidates.length > 0) {
          const cand = pendingCandidates.shift();
          await pc.addIceCandidate(new RTCIceCandidate(cand));
        }

        const answer = await pc.createAnswer();
        await pc.setLocalDescription(answer);

        console.log("📤 Sending SDP answer to camera");
        await channel.send({
          type: "broadcast",
          event: "signal",
          payload: {
            sender: "dashboard",
            type: "answer",
            answer: answer
          }
        });
        return;
      }

      // 3. Camera sends ICE Candidate
      if (payload.type === "ice") {
        if (!payload.candidate) return;

        if (peerConnection && peerConnection.remoteDescription && peerConnection.remoteDescription.type) {
          await peerConnection.addIceCandidate(new RTCIceCandidate(payload.candidate));
          console.log("✅ Camera ICE candidate added");
        } else {
          console.log("⏳ Queueing camera ICE candidate");
          pendingCandidates.push(payload.candidate);
        }
      }
    } catch (err) {
      console.error("Signaling error:", err);
      updateStatus("❌ Signaling error: " + err.message, "error");
    }
  })
  .subscribe((status) => {
    console.log("Supabase Realtime status:", status);
    if (status === "SUBSCRIBED") {
      updateStatus("📱 Waiting for mobile device to scan QR...", "waiting");
    }
  });